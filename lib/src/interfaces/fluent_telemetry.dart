import '../core/fluent_sqlite_internal.dart';
import '../utils/utils.dart';

/// Defines the logging interface for the database engine.
///
/// This abstract class provides a pluggable logging architecture, allowing
/// the application to redirect database diagnostic events to various outputs
/// (e.g., console, file, or remote crash reporting services like Sentry or Firebase).
abstract class FluentTelemetry {
  /// Global toggle for all database logging.
  bool get isLogOn;

  /// Determines if granular debug logs should be emitted.
  bool get isDebug;

  /// A catch-all hook for every log entry generated by the system.
  /// Useful for centralizing logs into a single custom telemetry stream.
  void Function(String msg, FluentLogLevel level, {String? tag})? get onAll;

  /// Hook for standard informational messages (e.g., initialization, task dispatch).
  void Function(String message)? get onInfo;

  /// Hook for developer-centric debug info (e.g., weight calculations, fingerprinting).
  void Function(String message)? get onDebug;

  /// Specialized hook for logging raw SQL queries and their bind parameters.
  /// Essential for monitoring query performance and debugging malformed SQL.
  void Function(String query, [List<Object?>? arguments])? get onSql;

  /// Hook for non-fatal performance warnings or unconventional database usage.
  void Function(String message)? get onWarning;

  /// Hook for capturing critical errors, exceptions, and associated stack traces.
  void Function(String message, Object e, StackTrace? s)? get onError;

  /// The primary logging sink that routes all diagnostic data to the configured
  /// logging implementation, enriched with metadata and context.
  ///
  /// [message]: The primary log entry.
  /// [level]: The severity level of the log (e.g., info, debug, error).
  /// [customTag]: A categorical tag to filter logs (e.g., 'coordinator', 'worker').
  /// [hint]: An actionable suggestion for resolving a warning or error.
  /// [context]: A dictionary of key-value pairs providing additional state
  ///            (e.g., task IDs, execution weights, or query parameters).
  void all(String message, FluentLogLevel level, {String? customTag, String? hint, Map<String, dynamic>? context});

  /// Logs informational events (e.g., task lifecycle transitions).
  /// Only active if [isLogOn] is true.
  void info(String message, {String? tag, Map<String, dynamic>? context}) {
    if (!isLogOn) return;
    onInfo?.call(message);
    all(message, FluentLogLevel.info, customTag: tag, context: context);
  }

  /// Logs granular debug information (e.g., weight calculation values, fingerprint data).
  /// Only active if both [isLogOn] and [isDebug] are true, ensuring that
  /// high-frequency log noise is suppressed in production environments.
  void debug(String message, {String? tag, Map<String, dynamic>? context}) {
    if (!isLogOn || !isDebug) return;
    onDebug?.call(message);
    all(message, FluentLogLevel.debug, customTag: tag, context: context);
  }

  /// Logs raw SQL queries and their bind parameters.
  ///
  /// Only active when both [isLogOn] and [isDebug] are enabled. This method
  /// formats the query with its arguments, creating a clear audit trail for
  /// debugging complex query performance or data integrity issues.
  void sql(String message, {List<Object?>? arguments, String? tag}) {
    if (!isLogOn || !isDebug) return;
    onSql?.call(message, arguments);

    final String msg = (arguments != null && arguments.isNotEmpty) ? '$message | Args: $arguments' : message;

    all(msg, FluentLogLevel.sql, customTag: tag);
  }

  /// Logs non-fatal operational issues.
  ///
  /// Useful for highlighting performance bottlenecks (e.g., long-running queries)
  /// or unusual schema states that don't warrant a crash but require developer attention.
  void warning(String message, {String? tag, String? hint, Map<String, dynamic>? context}) {
    if (!isLogOn) return;
    onWarning?.call(message);
    all(message, FluentLogLevel.warning, customTag: tag, hint: hint, context: context);
  }

  /// Logs critical runtime exceptions and system errors.
  ///
  /// Captures the error object and stack trace, routing them to the [onError]
  /// handler (e.g., crash reporting services). Always logged if [isLogOn] is true.
  void error(String message, Object error, StackTrace? stackTrace, {String? tag, String? hint, Map<String, dynamic>? context}) {
    if (!isLogOn) return;
    onError?.call(message, error, stackTrace);
    all(message, FluentLogLevel.error, customTag: tag, hint: hint, context: context);
  }

  /// Retrieves a comprehensive diagnostic report for a specific table.
  ///
  /// This bridges the gap between active logging and post-mortem analysis
  /// by returning a snapshot of performance metrics and table state from the [FluentTableStatsTracker].
  Future<String> dumpReport(String dbName, String tableName) async => await FluentTableStatsTracker().dumpReport(dbName, tableName);
}
